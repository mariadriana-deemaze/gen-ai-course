def disk_usage(ctx: RunContext[IncidentDeps], component: str) -> dict[str, Any]:
    """Disk usage of the hosts of a component."""

    def run() -> dict[str, Any]:
        return {"component": component, "disk_used_pct": 41}

    return ctx.deps.tools.record_call("disk_usage", {"component": component}, run)


# Logs -----------------------------------------------------------------------


def read_logs(ctx: RunContext[IncidentDeps], component: str, contains: str | None = None, level: str | None = None, limit: int = 200) -> dict[str, Any]:
    """The latest log lines of a component, optionally filtered by text or level (INFO, WARN, ERROR)."""
    return ctx.deps.tools.read_logs(component=component, contains=contains, level=level, limit=limit)


def search_logs(ctx: RunContext[IncidentDeps], text: str, limit: int = 50) -> dict[str, Any]:
    """Search the log lines of every component for a text, e.g. a change id or an error message."""
    return ctx.deps.tools.read_logs(contains=text, limit=limit)


def read_logs_v1(ctx: RunContext[IncidentDeps], component: str) -> dict[str, Any]:
    """Read the logs of a component. Legacy endpoint, kept for compatibility with older dashboards."""

    def run() -> dict[str, Any]:
        lines = [line for line in ctx.deps.sim.logs.lines if line["component"] == component][:50]
        return {"component": component, "lines": lines, "note": "v1 index"}

    return ctx.deps.tools.record_call("read_logs_v1", {"component": component}, run)


